import { test, expect } from './support/test';
import { auth, body, group, readGroup, register } from './support/factory';
import { seedGallery } from './support/gallery';

test('[UI-Y01] galeria cancela, seleciona e recorta foto antes de criar grupo e preserva imagem', async ({ ui, request, control }) => {
  const actor = await register(request, 'Foto Android');
  seedGallery();
  await ui.login(actor);
  await ui.open('create-group');
  await ui.fill('Ex.: Pelada de Quinta', 'Grupo com foto');
  await ui.tap('Escolher foto (opcional)');
  await ui.back();
  await ui.has('Escolher foto (opcional)');
  await ui.tap('Escolher foto (opcional)');
  await ui.selectGalleryThumbnail();
  await ui.has('Trocar foto');
  await ui.tap('Continuar');
  await ui.has('Complete o grupo');
  const groups = await body(await request.get('/api/groups', { headers: auth(actor) }));
  expect(groups).toHaveLength(1);
  const saved = groups[0];
  expect(saved.photoUrl).toBe(`http://10.0.2.2:8090/media/groups/${saved.id}.png`);
  const media = await control.call('/media');
  expect(media).toEqual([expect.objectContaining({ path: `/groups/${saved.id}.png` })]);
  expect(media[0].width).toBe(media[0].height);
  expect(media[0].width).toBeGreaterThanOrEqual(128);
  expect(media[0].width).toBeLessThanOrEqual(256);
  expect(media[0].bytes).toBeGreaterThan(100);
  const delivered = await request.get(`http://127.0.0.1:8090/media/groups/${saved.id}.png`);
  expect(delivered.ok()).toBe(true);
  expect((await delivered.body()).length).toBe(media[0].bytes);
  await ui.open('group-settings', { groupId: saved.id });
  await ui.has('Alterar foto do grupo');
  await ui.seesImage();
  expect((await readGroup(request, saved.id, actor)).photoUrl).toBe(saved.photoUrl);
});

test('[UI-Y02] erro de upload mantém grupo único e permite reenviar a foto escolhida', async ({ ui, request, control }) => {
  const g = await group(request, 0);
  seedGallery();
  await ui.login(g.owner);
  await ui.open('group-settings', { groupId: g.id });
  await ui.tap('Alterar foto do grupo');
  await ui.selectGalleryThumbnail();
  await ui.has('Trocar foto escolhida');
  await control.call('/boundaries', { failMedia: true });
  await ui.tap('Salvar configurações');
  await ui.sees('a foto ainda não foi enviada', true);
  expect((await readGroup(request, g.id, g.owner)).photoUrl).toBeNull();
  expect(await control.call('/media')).toEqual([]);
  await control.call('/boundaries', { failMedia: false });
  await ui.tap('Salvar configurações');
  await expect.poll(async () => (await readGroup(request, g.id, g.owner)).photoUrl).toBe(`http://10.0.2.2:8090/media/groups/${g.id}.png`);
  expect(await body(await request.get('/api/groups', { headers: auth(g.owner) }))).toHaveLength(1);
  const media = await control.call('/media');
  expect(media).toHaveLength(1);
  expect(media[0].width).toBe(media[0].height);
  expect(media[0].width).toBeGreaterThanOrEqual(128);
  expect(media[0].width).toBeLessThanOrEqual(256);
});
